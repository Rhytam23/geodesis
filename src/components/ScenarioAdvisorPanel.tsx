import { useEffect, useRef, useState } from 'react';
import { Sparkles } from 'lucide-react';
import { friendlyErrorMessage } from './AdvisorPanel';
import {
  getScenarioNarrative,
  AdvisorUnavailableError,
  type AdvisorResult,
  type ScenarioAdvisorInput,
} from '../services/aiAdvisor';

type State =
  | { status: 'idle' }
  | { status: 'loading' }
  | { status: 'done'; result: AdvisorResult }
  | { status: 'error'; message: string };

/**
 * What-if explainer: shows the simulated projections and lets Nemotron (via the
 * serverless /api/advisor) explain them in plain language. Narrative only; the
 * numbers come from the simulation and are never changed by the model.
 */
export default function ScenarioAdvisorPanel({ input }: { input: ScenarioAdvisorInput }) {
  const [state, setState] = useState<State>({ status: 'idle' });
  const abortRef = useRef<AbortController | null>(null);
  const key = JSON.stringify(input);

  // A new simulation run invalidates the previous explanation.
  useEffect(() => {
    abortRef.current?.abort();
    setState({ status: 'idle' });
  }, [key]);

  useEffect(() => () => abortRef.current?.abort(), []);

  const ask = async () => {
    abortRef.current?.abort();
    const controller = new AbortController();
    abortRef.current = controller;
    setState({ status: 'loading' });
    try {
      const result = await getScenarioNarrative(input, controller.signal);
      setState({ status: 'done', result });
    } catch (err) {
      if (controller.signal.aborted) return;
      setState({
        status: 'error',
        message:
          err instanceof AdvisorUnavailableError
            ? friendlyErrorMessage(err)
            : 'AI advisor is temporarily unavailable. The simulation results above are unaffected.',
      });
    }
  };

  return (
    <div className="rounded-3xl border border-slate-200 bg-white p-4 text-sm">
      <div className="flex items-start justify-between gap-3">
        <div>
          <div className="uppercase text-xs tracking-wider font-semibold text-slate-500">What-if scenario</div>
          <div className="mt-0.5 font-semibold text-slate-900">{input.name}</div>
          <div className="text-xs text-slate-500">
            Rainfall {input.parameters.rainfallDelta}% • Salinity +{input.parameters.salinityDelta} dS/m • AWD{' '}
            {input.parameters.awdAdoption}%
          </div>
        </div>
        <span className="shrink-0 rounded-full bg-amber-50 px-2 py-0.5 text-[10px] font-semibold text-amber-700 border border-amber-200">
          SIMULATED
        </span>
      </div>

      <table className="mt-3 w-full text-xs">
        <thead>
          <tr className="text-left text-slate-500">
            <th className="py-1 font-medium">Year</th>
            <th className="py-1 font-medium">Yield (t/ha)</th>
            <th className="py-1 font-medium">Water (m³/ha)</th>
            <th className="py-1 font-medium">Risk</th>
          </tr>
        </thead>
        <tbody>
          {input.projections.map((p) => (
            <tr key={p.year} className="border-t border-slate-100">
              <td className="py-1.5 font-medium text-slate-900">{p.year}</td>
              <td className="py-1.5">{p.yield}</td>
              <td className="py-1.5">{p.waterUse.toLocaleString()}</td>
              <td className="py-1.5">{p.riskScore}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <div className="mt-3 flex flex-col gap-2">
        <div className="text-[10px] uppercase tracking-wider font-semibold text-slate-500">Nemotron on Nebius</div>
        <button
          onClick={ask}
          disabled={state.status === 'loading'}
          className="flex w-full items-center justify-center gap-1.5 px-4 py-2 rounded-full border border-emerald-200 text-emerald-700 font-semibold text-xs hover:bg-emerald-50 disabled:opacity-60"
        >
          <Sparkles className="w-3.5 h-3.5" />
          {state.status === 'loading' ? 'ASKING...' : 'EXPLAIN THIS SCENARIO'}
        </button>
      </div>

      {state.status === 'done' && (
        <div className="mt-3">
          <div className="leading-snug whitespace-pre-line">{state.result.advice}</div>
          <div className="mt-2 text-xs text-slate-500">
            Generated by {state.result.model} via {state.result.provider || 'Nebius Token Factory'}. Narrative only; the simulated numbers are not changed.
          </div>
        </div>
      )}
      {state.status === 'error' && (
        <div className="mt-3 text-xs text-amber-700" role="alert">{state.message}</div>
      )}
    </div>
  );
}
